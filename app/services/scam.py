"""«Это реальное объявление или схема?» (владелец 25.10). Признаки частых схем — предупреждение в карточке заявки.

Заявку не прячем (бывают и настоящие с предоплатой), а честно пишем, что насторожило. Человек решает сам:
«🚫 Спам / схема» под заявкой — скрыть и (после голосов или нажатия админа) запомнить автора и текст.
"""
import re

_SIGNS: list[tuple[str, str]] = [
    (r"\bпредоплат\w*|\bоплат\w*\s+(вперёд|вперед|заранее)|\bзалог\w*\s+за\s+(материал|работ)", "просят предоплату"),
    (r"\b(переведи|переведите|скиньте|скинь)\b.{0,30}\b(карт|руб|₽|\d{3,})", "просят перевести деньги"),
    (r"\b(usdt|криптовалют\w*|крипт\w*|биткоин\w*|btc|trc-?20|кошел[её]к)", "оплата в криптовалюте"),
    (r"(bit\.ly|clck\.ru|tinyurl|goo\.gl|forms\.gle|wa\.me|cutt\.ly|t\.me/\+|joinchat)", "ссылка на сторонний сайт или закрытый чат"),
    (r"\b(код\s+из\s+смс|смс[- ]?код|данные\s+карты|cvv|cvc|паспорт\w*\s+данн)", "просят код из СМС, данные карты или паспорта"),
    (r"\b(\d[\d\s]{2,})\s*(₽|руб\w*|р\.?)\s*(в\s+день|за\s+день|в\s+час|за\s+час)\b", "обещают крупную оплату в день или час"),
    (r"\b(легк\w+|прост\w+)\s+(заработ\w*|задани\w*|работ\w*)", "«лёгкий заработок»"),
    (r"\b(дроп\w*|обнал\w*|карт\w*\s+на\s+(себя|своё\s+имя)|оформить\s+карт\w*)", "просят оформить карту или счёт на себя"),
    (r"\b(отзыв\w*|лайк\w*|подписк\w*)\s+за\s+(деньги|оплату|\d)", "оплата за отзывы или лайки"),
    (r"\b(срочно|сегодня)\b.{0,40}\b(деньги\s+сразу|оплата\s+сразу|сразу\s+на\s+карту)", "давят срочностью и «деньгами сразу»"),
]
_RE = [(re.compile(p, re.I), why) for p, why in _SIGNS]


def signs(text: str) -> list[str]:
    """Что насторожило (без повторов, по порядку)."""
    out: list[str] = []
    for rx, why in _RE:
        if rx.search(text or "") and why not in out:
            out.append(why)
    return out


def warning(text: str) -> str:
    """Строка для карточки заявки или пусто."""
    found = signs(text)
    if not found:
        return ""
    return ("⚠️ <b>Осторожно, возможна схема:</b> " + ", ".join(found)
            + ". Не платите вперёд и не сообщайте коды; если это обман — «🚫 Спам / схема».")
