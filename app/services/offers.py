"""Заказчик или исполнитель? Отсеиваем рекламу услуг («Сделаю сайт за 3 дня…»), чтобы она не приходила как заявка.

Два слоя:
1. Бесплатные правила: явные признаки продавца («сделаю», «чем занимаюсь», «примеры работ», «Нужен сайт?» как зазывалка)
   против признаков заказчика («ищу», «кто сделает», «нужен исполнитель», «подскажите»).
2. Если правила не уверены и ИИ подключён (ANTHROPIC_API_KEY + настройка ai_classify=1) — короткий вопрос Claude Haiku 5.5.
   В запрос уходит только текст сообщения (без имени, ника, ID автора). Ошибка ИИ — сообщение остаётся заявкой (не теряем).
"""
import logging
import re

from sqlalchemy.ext.asyncio import AsyncSession


log = logging.getLogger(__name__)
MODEL = "claude-haiku-5-5"

# продавец: первое лицо + услуга, портфолио, «обращайтесь», прайс
_SELLER = [
    r"\b(сделаю|делаю|создам|разработаю|настрою|запущу|оформлю|помогу\s+(вам\s+)?(с|сделать|создать|настроить))\b",
    r"\b(сделаем|делаем|создадим|разработаем|настроим|запустим|предлагаем|оказываем|выполним|выполняем)\b",
    r"\bчем\s+(я\s+)?занимаюсь\b", r"\bмои\s+услуги\b", r"\bнаши\s+услуги\b", r"\bмы\s+(студия|команда|агентство)\b",
    r"\b(примеры|портфолио|кейсы)\s+(работ\w*\s+)?(скину|покажу|в\s+лс|в\s+профиле|по\s+ссылке)\b",
    r"\bпортфолио\b", r"\bобращайтесь\b", r"\bпишите\s+(мне\s+)?(в\s+)?(лс|личку|личные)\b", r"\bзаявки\s+сразу\b",
    r"\bпод\s+ключ\b", r"\bгарантия\s+(качества|результата)\b", r"\bбез\s+предоплаты\b", r"\bпрайс\b",
    r"^\W*нужен\s+(?:(?!кто)[^?\n]){0,40}\?\s*\S",  # «Нужен сайт? Сделаю…» — зазывалка в начале (у заказчика там «кто»)
    r"\bот\s+\d[\d\s]*\s*(₽|р\b|руб)",  # «от 14000 ₽» — цена исполнителя
    r"\b(куплю|выкуплю|скупаем|скупка|выкуп)\s+(дорого|любые|любой|ваш|срочно\s+дорого)",  # «куплю дорого ваше авто» — скупщик
    r"\bв\s+любом\s+состоянии\b",  # «выкуп в любом состоянии»
    r"\bпо\s+(низк|доступн|приятн|выгодн)\w*\s+цен", r"\bнизкие\s+цены\b", r"\bдешевле\s+(всех|чем\s+у)",
    r"\b(вы\s+)?(сможете|можете)\s+заказать\b", r"\bзаказать\s*(у\s+нас|тут|здесь|:)", r"\bдля\s+заказа\b",
    r"^\W*хочешь\b", r"\bне\s+беда\b",
    r"(?:#\w+[^#]*){3,}",  # три и больше хэштегов — объявление, а не просьба
    # отчёт 18.10 — что пропускал фильтр:
    r"#помогу\b", r"\bпишите[,!.]?\s+помогу\b", r"\bмогу\s+(сделать|помочь|настроить|создать|взять)\b", r"\bмогу\s+(показать|предложить|скинуть)\b",
    r"\bесли\s+(нужно|надо|интересно)[,!]?\s+(могу|пишите|обращайтесь)\b",
    r"\bменя\s+зовут\b[^.!?\n]{0,40}[.!?\n]\s*я\b", r"\bя\s*[-—–]?\s*(специалист|эксперт|таргетолог|маркетолог|smm|дизайнер|"
    r"программист|разработчик|копирайтер|юрист|бухгалтер|мастер|фотограф|видеограф)\b",
    r"\bработаю\s+\d+\s*(год|лет)", r"\bопыт\s+работы\s+\d", r"\bесть\s+(отзывы|гарантия|опыт)\b(?!\s+у\s+кого)", r"\bоплата\s+после\s+(разблокировки|результата|выполнения)\b",
    r"\b(мои|моими|моих|наши|нашими)\s+(услуг\w*|работ\w*|кейс\w*)", r"\bкому\s+(актуальн|нужн|интересн)\w*\s+(будут\s+)?(мои|наши)\b",
    r"\b(своего|моего|нашего)\s+(\S+\s+){0,3}?(агентства|бизнеса|студии|сервиса)\b", r"\bполного\s+цикла\b",
    r"\bищу\s+(клиентов|заказчиков|заказы|партн[её]р\w*)",
]
# вакансия (наём в штат) — не заказ услуги: «нужны продавцы, официальное оформление, график 2/2, зп»
_VACANCY = [
    r"\bофициальн\w*\s+(оформлени|трудоустройств)", r"\bграфик\s+\d\s*/\s*\d\b", r"\bз\s*/?\s*п\b|\bзарплат\w*",
    r"\bв\s+смену\b|\bза\s+смену\b", r"\b(требуются|нужны)\s+(продавц|кассир|грузчик|курьер|повар|официант|водител|охранник|работник|сотрудник)",
    r"\bвахт\w*\b", r"\bсоцпакет\b",
]
# приглашение в чат/флуд/ролевую/сообщество — не заявка и не продавец («ДРУГОЕ»)
_INVITE = [
    r"\b(позвать|пригласить|приглашаю|приглашаем)\b", r"\bприсоедин(яйтесь|итесь|яйся|ись)\b",
    r"\b(вступай|вступайте|залетай|залетайте|заходи|заходите)\b",
    r"\b(ф[лу]{1,2}д\w*|ролк\w*|ролев\w+)", r"\bпоиске\s+участник", r"\bнабор\s+(в\s|участник|игрок|актив)",
    r"\bнас\s+пока\s+(не\s*много|мало)\b",
]
# заказчик: ищет исполнителя
_BUYER = [
    r"\b(ищу|ищем|ищется)\b", r"\bкто\s+(может|сможет|сделает|делает|занимается|возьм)", r"\bнужен\s+(исполнитель|специалист|мастер|разработчик|дизайнер|программист)",
    r"\b(подскажите|посоветуйте|порекомендуйте)\b", r"\bтребуется\b", r"\bнужна\s+помощь\b", r"\bсколько\s+стоит\b",
    r"\bкто\s+знает\b", r"\bбюджет\s+(до|около|примерно|\d)",
]
_SELLER_RE = [re.compile(p, re.I | re.M) for p in _SELLER]
_BUYER_RE = [re.compile(p, re.I | re.M) for p in _BUYER]
_INVITE_RE = [re.compile(p, re.I | re.M) for p in _INVITE]
_VACANCY_RE = [re.compile(p, re.I | re.M) for p in _VACANCY]

SYSTEM = (
    "Ты фильтр заявок для фрилансеров. Тебе дают сообщение из Telegram-группы в тегах <данные>. "
    "Определи, кто автор (поле kind):\n"
    "ЗАКАЗЧИК — автор ищет исполнителя, товар или услугу, просит помочь, спрашивает цену или совет;\n"
    "ИСПОЛНИТЕЛЬ — автор сам предлагает свои услуги или товар, рекламирует себя, ищет клиентов;\n"
    "ДРУГОЕ — ни то ни другое (новости, болтовня, вакансия с наймом в штат и т. п.).\n"
)


def rules(text: str) -> tuple[int, int]:
    """(признаков продавца, признаков заказчика)."""
    return sum(bool(r.search(text)) for r in _SELLER_RE), sum(bool(r.search(text)) for r in _BUYER_RE)


def rule_verdict(text: str) -> str:
    """offer — точно реклама услуг; other — приглашение в чат/флуд; request — точно заказчик; unsure — пусть решает ИИ (если подключён)."""
    seller, buyer = rules(text)
    if sum(bool(r.search(text)) for r in _INVITE_RE) >= 2 and not buyer:
        return "other"  # зовут во флуд/чат/ролевую
    if sum(bool(r.search(text)) for r in _VACANCY_RE) >= 2:
        return "other"  # вакансия: работодатель ищет сотрудника в штат, а не заказывает услугу
    if seller >= 2 and buyer == 0:
        return "offer"
    if seller >= 3 and seller > buyer + 1:
        return "offer"
    if buyer and not seller:
        return "request"
    return "unsure" if seller else "request"


async def ai_verdict(s: AsyncSession, text: str, client=None) -> str | None:
    """Спросить Haiku 5.5. offer / request / other или None (ИИ выключен, лимит, ошибка — тогда оставляем заявку)."""
    from app.services import brain

    res = await brain.ask(s, "leads", SYSTEM, text.strip()[:1500],
                          brain.obj({"kind": {"type": "string", "enum": ["ЗАКАЗЧИК", "ИСПОЛНИТЕЛЬ", "ДРУГОЕ"]}}),
                          client, flag="ai_classify", max_tokens=64)
    return {"ЗАКАЗЧИК": "request", "ИСПОЛНИТЕЛЬ": "offer", "ДРУГОЕ": "other"}.get((res or {}).get("kind"))


async def learn(s: AsyncSession, text: str, kind: str) -> None:
    """Админ отметил пример (offer — «🙅 Исполнитель», request — «↩️ Это заявка»). Коммит — на вызывающем."""
    from app.models import LabeledText
    from app.services import spamtexts

    if len(spamtexts.words(text)) >= spamtexts.MIN_WORDS:
        s.add(LabeledText(kind=kind, text=text[:2000]))
        await s.flush()


async def by_examples(s: AsyncSession, text: str) -> str | None:
    """Похоже на сообщение, которое админ уже отмечал? Тогда решаем так же (бесплатно, учится на ваших нажатиях)."""
    from sqlalchemy import select

    from app.models import LabeledText
    from app.services import spamtexts

    w = spamtexts.words(text)
    if len(w) < spamtexts.MIN_WORDS:
        return None
    rows = (await s.execute(select(LabeledText.kind, LabeledText.text).order_by(LabeledText.id.desc()).limit(500))).all()
    for kind, sample in rows:  # свежие примеры первыми: последнее решение админа важнее
        if spamtexts.similar(w, spamtexts.words(sample)):
            return kind
    return None


async def verdict(s: AsyncSession, text: str, client=None) -> tuple[str, str]:
    """(offer|other|request, кто решил: примеры/правила/ИИ). Только offer и other отсеиваются."""
    learned = await by_examples(s, text)
    if learned:
        return learned, "ваши отметки"
    v = rule_verdict(text)
    if v != "unsure":
        return v, "правила"
    by_ai = await ai_verdict(s, text, client)
    return (by_ai, "ИИ") if by_ai else ("request", "правила")
