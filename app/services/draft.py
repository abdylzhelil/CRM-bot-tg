"""Простой «умный» черновик ответа клиенту — по правилам, без ИИ и без затрат.

Берёт шаблон и цены пользователя, подставляет имя, тему заявки (по нише), бюджет и срочность из текста заявки и добавляет
уточняющий вопрос под нишу. Каждое нажатие «Другой вариант» выбирает другие формулировки.
"""
import random
import re

from app.services import quiet, templates

TOPIC = {
    "Сайты": "по сайту", "Боты": "по боту", "Реклама": "по рекламе", "Недвижимость": "по помещению",
    "SMM": "по ведению соцсетей", "Дизайн": "по дизайну", "Avito": "по Авито", "Автоматизация": "по автоматизации",
}
QUESTIONS = {
    "Сайты": ["Какая задача: визитка, лендинг или магазин? Есть ли примеры сайтов, которые нравятся?",
              "Для какого бизнеса сайт и к какому сроку он нужен?"],
    "Боты": ["Что должен уметь бот: принимать заказы, отвечать на вопросы, вести запись?",
             "Где бот будет работать — в Telegram, WhatsApp или в обоих?"],
    "Реклама": ["Что именно продвигаем и в какой аудитории — в каком городе и в каких группах?",
                "Какой бюджет на рекламу и какой результат ждёте?"],
    "Недвижимость": ["Какая площадь и район нужны, на какой срок?", "Какой бюджет и когда планируете смотреть?"],
    "SMM": ["Какие соцсети ведём и сколько постов в неделю нужно?", "Есть ли уже страница и какая тематика?"],
    "Дизайн": ["Что нужно сделать: логотип, баннер, карточки? Есть ли примеры, которые нравятся?",
               "К какому сроку нужен результат и в каком формате?"],
    "Avito": ["Сколько объявлений и какой товар или услуга?", "Есть ли уже аккаунт, и в каком городе продаёте?"],
    "Автоматизация": ["Какой процесс хотите автоматизировать и чем сейчас пользуетесь?",
                      "Сколько заявок или клиентов в день проходит через этот процесс?"],
}
DEFAULT_QUESTIONS = ["Расскажите немного подробнее о задаче и желаемом сроке.",
                     "Что для вас важнее всего в результате и к какому сроку он нужен?"]
OPENINGS = ["Здравствуйте{, имя}! Увидел ваш запрос {тема}.", "Добрый день{, имя}! Заметил ваше сообщение {тема}.",
            "Здравствуйте{, имя}! Ваш запрос {тема} как раз по моей части."]
CLOSINGS = ["Когда вам удобно обсудить — переписка или звонок?", "Могу сразу предложить вариант, как только уточним детали.",
            "Напишите, и я подготовлю предложение под вашу задачу."]
BUDGET = re.compile(r"(\d[\d\s]{0,8}\d|\d)\s*(к\b|тыс\w*|т\.?\s?р\b|₽|руб\w*|р\b)", re.I)
URGENT = re.compile(r"(срочн\w*|сегодня|завтра|прямо сейчас|горит|asap)", re.I)


def find_budget(text: str) -> str:
    """«бюджет 30к», «до 50 000 руб», «15 тыс» -> «30 тыс. ₽», «50000 ₽», «15 тыс. ₽»."""
    m = BUDGET.search(text)
    if not m:
        return ""
    num = re.sub(r"\s+", "", m.group(1))
    unit = m.group(2).lower()
    return f"{num} тыс. ₽" if unit.startswith(("к", "тыс", "т")) else f"{num} ₽"


def build(lead_text: str, lead_name: str, root: str, template: str, prices: str, rng: random.Random | None = None) -> str:
    rng = rng or random
    first = lead_name.split()[0] if lead_name.strip() else ""
    topic = TOPIC.get(root, "по вашей задаче")
    question = rng.choice(QUESTIONS.get(root, DEFAULT_QUESTIONS))
    budget = find_budget(lead_text)
    notes = []
    if URGENT.search(lead_text):
        notes.append("Понимаю, что срочно — готов приступить без долгих пауз.")
    if budget:
        notes.append(f"Вижу, ориентир по бюджету — {budget}; подберу вариант под него.")
    if template.strip():  # у человека есть свой шаблон — оставляем его стиль, добавляем контекст заявки
        base = templates.render(template, name=lead_name, group="", category=root.lower() or "эта услуга", prices=prices)
        return "\n".join([base, *notes, question])
    lines = [rng.choice(OPENINGS).replace("{, имя}", f", {first}" if first else "").replace("{тема}", topic)]
    lines += notes
    if prices.strip():
        lines.append(f"Цены: {prices.strip()}")
    lines += [question, rng.choice(CLOSINGS)]
    return "\n".join(lines)
