async def _add_tree(session: AsyncSession, emoji: str, name: str, subs, words, strong, city) -> None:
    """Добавить одну нишу с подкатегориями и словами (без коммита)."""
    cat = Category(name=name, emoji=emoji, city=city, section=SECTION_OF.get(name, ""))
    session.add(cat)
    await session.flush()
    for sub in subs:
        session.add(Category(name=sub, parent_id=cat.id, emoji=emoji))
    for w in words:
        session.add(Keyword(kind="category", word=w, category_id=cat.id))
    for w in strong:
        session.add(Keyword(kind="strong", word=w, category_id=cat.id))


SEEN_KEY = "seed_niches"  # ниши, которые уже добавлялись: удалённую админом нишу не возвращаем


async def add_missing(session: AsyncSession) -> list[str]:
    """Добавить в работающую базу ниши из TREE, которых ещё нет (по названию). Правки админа не трогаем.
    Нишу, которую админ однажды удалил, заново не добавляем (список в settings, ключ seed_niches)."""
    from app.models import Setting

    row = await session.get(Setting, SEEN_KEY)
    seen = set(filter(None, (row.value if row else "").split("|")))
    have = {n.lower() for n in (await session.scalars(select(Category.name).where(Category.parent_id.is_(None)))).all()}
    added = []
    # раздел у старых ниш (у которых он ещё не задан) — по названию
    for cat in (await session.scalars(select(Category).where(Category.parent_id.is_(None), Category.section == ""))).all():
        if cat.name in SECTION_OF:
            cat.section = SECTION_OF[cat.name]
    for emoji, name, subs, words, strong, city in TREE:
        if name.lower() not in have and name not in seen:
            await _add_tree(session, emoji, name, subs, words, strong, city)
            added.append(name)
        seen.add(name)
    value = "|".join(sorted(seen))
    if row:
        row.value = value
    else:
        session.add(Setting(key=SEEN_KEY, value=value))
    # общие минус-слова: один раз убрать вредные и добавить новые (потом админ правит сам — не трогаем)
    if await session.get(Setting, NEGATIVES_KEY) is None:
        glob = (await session.scalars(select(Keyword).where(Keyword.kind == "negative", Keyword.category_id.is_(None)))).all()
        have_n = {k.word.casefold() for k in glob}
        for k in glob:
            if k.word.casefold() in NEGATIVES_REMOVED:
                await session.delete(k)
                added.append(f"убрано минус-слово «{k.word}»")
        for w in NEGATIVES:
            if w.casefold() not in have_n:
                session.add(Keyword(kind="negative", word=w))
                added.append(f"минус-слово «{w}»")
        session.add(Setting(key=NEGATIVES_KEY, value="1"))
    # новые слова-намерения — тоже только недостающие и только один раз
    irow = await session.get(Setting, INTENTS_KEY)
    iseen = set(filter(None, (irow.value if irow else "").split("|")))
    have_i = {w.casefold() for w in (await session.scalars(select(Keyword.word).where(Keyword.kind == "intent"))).all()}
    for w in INTENTS:
        if w.casefold() not in have_i and w not in iseen:
            session.add(Keyword(kind="intent", word=w))
            added.append(f"намерение «{w}»")
        iseen.add(w)
    ivalue = "|".join(sorted(iseen))
    if irow:
        irow.value = ivalue
    else:
        session.add(Setting(key=INTENTS_KEY, value=ivalue))
    await session.commit()
    if added:
        from app.services import rules

        rules.invalidate()
    return added


async def seed(session: AsyncSession) -> None:
    from app.services import junk

    await junk.mark_existing(session)
    from app.scout import captchas

    await captchas.restore_skipped(session)
    from app.scout import search

    await search.requeue_small_home(session)
    if await session.scalar(select(func.count()).select_from(Category)):
        await add_missing(session)
        return
    for w in INTENTS:
        session.add(Keyword(kind="intent", word=w))
    for w in NEGATIVES:
        session.add(Keyword(kind="negative", word=w))
    for q in QUERIES:
        session.add(SearchQuery(text=q))
    for emoji, name, subs, words, strong, city in TREE:
        await _add_tree(session, emoji, name, subs, words, strong, city)
    await session.commit()
    await add_missing(session)  # запомнить, какие ниши уже были
