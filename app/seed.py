async def _add_tree(session: AsyncSession, emoji: str, name: str, subs, words, strong, city) -> None:
    """Добавить одну нишу с подкатегориями и словами (без коммита)."""
    cat = Category(name=name, emoji=emoji, city=city)
    session.add(cat)
    await session.flush()
    for sub in subs:
        session.add(Category(name=sub, parent_id=cat.id, emoji=emoji))
    for w in words:
        session.add(Keyword(kind="category", word=w, category_id=cat.id))
    for w in strong:
        session.add(Keyword(kind="strong", word=w, category_id=cat.id))


SEEN_KEY = "seed_niches"  # ниши, которые уже добавлялись: удалённую админом нишу не возвращаем


async def add_missing(session: AsyncSession) -> list[str]:
    """Добавить в работающую базу ниши из TREE, которых ещё нет (по названию). Правки админа не трогаем.
    Нишу, которую админ однажды удалил, заново не добавляем (список в settings, ключ seed_niches)."""
    from app.models import Setting

    row = await session.get(Setting, SEEN_KEY)
    seen = set(filter(None, (row.value if row else "").split("|")))
    have = {n.lower() for n in (await session.scalars(select(Category.name).where(Category.parent_id.is_(None)))).all()}
    added = []
    for emoji, name, subs, words, strong, city in TREE:
        if name.lower() not in have and name not in seen:
            await _add_tree(session, emoji, name, subs, words, strong, city)
            added.append(name)
        seen.add(name)
    value = "|".join(sorted(seen))
    if row:
        row.value = value
    else:
        session.add(Setting(key=SEEN_KEY, value=value))
    await session.commit()
    if added:
        from app.services import rules

        rules.invalidate()
    return added


async def seed(session: AsyncSession) -> None:
    if await session.scalar(select(func.count()).select_from(Category)):
        await add_missing(session)
        return
    for w in INTENTS:
        session.add(Keyword(kind="intent", word=w))
    for w in NEGATIVES:
        session.add(Keyword(kind="negative", word=w))
    for q in QUERIES:
        session.add(SearchQuery(text=q))
    for emoji, name, subs, words, strong, city in TREE:
        await _add_tree(session, emoji, name, subs, words, strong, city)
    await session.commit()
    await add_missing(session)  # запомнить, какие ниши уже были
